#!/bin/bash
# make-steam-shortcut.sh — build a double-clickable "S734M.app", the Windows Steam: it opens Steam's
# VISIBLE window in the storefront wrapper (wine 11.0), with Steam's own icon.
#
# The name (docs/plans/launcher-window.md, 2.4): S734M, so that it is never taken for Valve's own
# Steam.app. Spotlight also finds it as "Windows Steam", "Steam Store" and "CS2 Steam Store", its
# alternate names; plain "Steam" is Valve's app's name and is not one of them. Its Info.plist carries
# L1Role steam and L1Prefix, the store wrapper's prefix, which the 14unch3r window reads. Until
# 2026-11 the app was "CS2 Steam Store.app": a build removes that one from the same folder when this
# script made it and it is not the app just built, and says so.
#
# Why it exists: the self-built 11.16 engine is the play wrapper, but Steam's visible storefront
# is black on it (embedded Chromium never rendered on stock Wine here — GOTCHAS, dxmt#141). The
# Porting Kit 11.0 engine renders the store fine, and Steam licences are account-level, so the
# split costs nothing: play in the 11.16 wrapper, shop in the 11.0 one. This app is the "shop"
# double-click; the existing "Cities Skylines II.app" stays the "play" one.
#
# If the storefront wrapper doesn't exist yet, this script CREATES it from the daily wrapper:
#   1. `cp -c` APFS clone — instant, shares disk (GOTCHAS § "du lies about disk on APFS")
#   2. restores the original 11.0 engine inside the clone from the wine.pk11.0-BAK that
#      build-engine-1116.sh leaves behind (the clone must NOT run 11.16 — black storefront)
#   3. removes the game install from the clone — tree AND appmanifest together, so its Steam
#      neither re-downloads nor tries to update a second copy (the store wrapper only needs
#      Steam itself; game licences don't care which wrapper bought them)
#
# Usage:
#   bash scripts/make-steam-shortcut.sh                  # default paths, creates wrapper if needed
#   --wrapper /path/Store.app      storefront wrapper (default ~/Applications/CS2dxmt11-pk110.app)
#   --from /path/Daily.app         clone donor when creating (default ~/Applications/CS2dxmt11.app)
#   --name "S734M"                 app name        --dest ~/Applications
#
# Safe to re-run: replaces its own .app bundle and nothing else, and refuses anything else at the
# target, before it clones or removes anything: a Wine wrapper named S734M.app above all. --name must
# not be empty, hold / or a control character, or start with . or -. Skips the clone if the
# storefront wrapper already exists.
set -u

DEST="$HOME/Applications"
APPNAME="S734M"
WRAPPER="$HOME/Applications/CS2dxmt11-pk110.app"
DONOR="$HOME/Applications/CS2dxmt11.app"
MARK="# Generated by scripts/make-steam-shortcut.sh"   # the shim's line 2; with the identifier, how own_bundle knows its own
BUNDLE_ID="local.cs2.steamstore"                        # unchanged by the rename: macOS keeps its consent records by it

need_value() {   # <option> [<value> ...]: an option that takes a value must be given a non-empty one
  if [ $# -lt 2 ] || [ -z "$2" ]; then echo "$1 needs a value"; exit 2; fi
}
check_name() {   # <name>: it becomes a file name in --dest and the app's name, so it is checked before anything is removed
  case "$1" in
    ''|*/*|.*|-*|*[[:cntrl:]]*) echo "--name must not be empty, hold / or a control character, or start with . or -"; exit 2 ;;
  esac
}
# A builder replaces only its own bundle. Absent is fine; anything else must be a folder and not a symlink,
# have no Contents/SharedSupport (every Wine wrapper has one), hold a plain-file shim one of whose first ten
# lines begins with this builder's marker, and carry this builder's bundle identifier. The marker and the
# identifier never change: macOS keeps its consent records by the identifier, and this test relies on both.
own_bundle() {   # <target> <marker> <bundle identifier>: 0 when the target is absent or this builder's own
  local t="$1" s id
  [ -e "$t" ] || [ -L "$t" ] || return 0
  { [ -d "$t" ] && [ ! -L "$t" ]; } || return 1
  { [ ! -e "$t/Contents/SharedSupport" ] && [ ! -L "$t/Contents/SharedSupport" ]; } || return 1
  s="$t/Contents/MacOS/launch"
  { [ -f "$s" ] && [ ! -L "$s" ]; } || return 1
  head -n 10 "$s" 2>/dev/null | awk -v m="$2" 'index($0, m) == 1 { f = 1 } END { exit !f }' || return 1
  id=$(plutil -extract CFBundleIdentifier raw "$t/Contents/Info.plist" 2>/dev/null) || return 1
  [ "$id" = "$3" ]
}

while [ $# -gt 0 ]; do
  case "$1" in
    --wrapper) need_value "$@"; WRAPPER="$2"; shift 2 ;;
    --from)    need_value "$@"; DONOR="$2"; shift 2 ;;
    --dest)    need_value "$@"; DEST="$2"; shift 2 ;;
    --name)    need_value "$@"; APPNAME="$2"; shift 2 ;;
    -h|--help) sed -n '2,/^set -u$/p' "$0" | sed '$d'; exit 0 ;;
    *) echo "unknown option: $1 (try --help)"; exit 2 ;;
  esac
done
check_name "$APPNAME"

APP="$DEST/$APPNAME.app"
if ! own_bundle "$APP" "$MARK" "$BUNDLE_ID"; then
  echo "ERROR: $APP exists and was not built by this script; nothing removed"
  echo "If it is a leftover of this script, move it to the Trash and run this again."
  if [ -e "$APP/Contents/SharedSupport" ] || [ -L "$APP/Contents/SharedSupport" ]; then
    echo "A Wine wrapper of that name is in this folder. Move or remove it (see surviving-mars-relaunched/README.md), or build under another name with --name."
  fi
  exit 1
fi

SS="$WRAPPER/Contents/SharedSupport"
APPID=949230   # Cities: Skylines II (appmanifest_228980 = Steamworks redistributables — leave it; its files stay)

# ------------------------------------------------- create the storefront wrapper if missing
if [ ! -d "$SS/prefix" ]; then
  DSS="$DONOR/Contents/SharedSupport"
  [ -d "$DSS/prefix" ] || { echo "ERROR: no storefront wrapper at $WRAPPER and no donor at $DONOR — install the base stack first (INSTALL.md), or pass --from"; exit 1; }
  # refuse to clone out from under a live Steam — cmdline pgrep misses Windows-argv steam, so
  # attribute by open files against the donor prefix (measured 2026-08-24)
  for _p in $(pgrep -f "steam" 2>/dev/null); do
    lsof -p "$_p" 2>/dev/null | grep -q "$DSS/prefix" && \
      { echo "ERROR: Steam is running in $(basename "$DONOR") — quit it first (steam.exe -shutdown; never kill -9)."; exit 1; }
  done
  echo "Storefront wrapper not found — creating it from $(basename "$DONOR") (APFS clone, seconds, ~no extra disk):"
  cp -Rc "$DONOR" "$WRAPPER" || { echo "ERROR: clone failed (same APFS volume required)"; rm -rf "$WRAPPER"; exit 1; }
  if [ -d "$SS/wine.pk11.0-BAK" ]; then
    # donor was already engine-swapped to 11.16 — put the original 11.0 engine back IN THE CLONE
    rm -rf "$SS/wine"
    mv "$SS/wine.pk11.0-BAK" "$SS/wine"
    echo "  engine: restored wine 11.0 inside the clone (from wine.pk11.0-BAK)"
  fi
  GDIR_CLONE="$SS/prefix/drive_c/Program Files (x86)/Steam/steamapps"
  rm -rf "$GDIR_CLONE/common/Cities Skylines II"
  rm -f  "$GDIR_CLONE/appmanifest_$APPID.acf"
  echo "  game:   removed from the clone (tree + appmanifest together — Steam won't re-fetch)"
fi

# ------------------------------------------------- preflight
WINE64="$SS/wine/bin/wine64"
STEAM_EXE="$SS/prefix/drive_c/Program Files (x86)/Steam/steam.exe"
[ -x "$WINE64" ]    || { echo "ERROR: no wine64 inside $(basename "$WRAPPER") — wrapper looks incomplete"; exit 1; }
[ -f "$STEAM_EXE" ] || { echo "ERROR: Steam is not installed inside $(basename "$WRAPPER") (INSTALL.md step 2)"; exit 1; }
WV="$("$WINE64" --version 2>/dev/null)"
case "$WV" in
  *11.16*) echo "WARNING: this wrapper runs $WV — Steam's storefront is known BLACK on the 11.16 engine (that's the whole reason for the wrapper split). Point --wrapper at a wine 11.0 wrapper." ;;
esac

echo "=== building $APP ==="
echo "    wrapper: $WRAPPER ($WV)"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# ------------------------------------------------- launch shim
# The app's name and the wrapper's path reach the shim through printf %q, between the two quoted
# heredocs, so that no character of either is ever run; and each osascript call takes its text and
# the title as arguments, as the launchers' launch-feedback block does, never as AppleScript source.
cat > "$APP/Contents/MacOS/launch" << 'SHIM'
#!/bin/bash
# Generated by scripts/make-steam-shortcut.sh — re-run that instead of editing this file.
SHIM
printf 'TITLE=%q\n' "$APPNAME" >> "$APP/Contents/MacOS/launch"
printf 'WRAPPER=%q\n' "$WRAPPER" >> "$APP/Contents/MacOS/launch"
cat >> "$APP/Contents/MacOS/launch" << 'SHIM'
SS="$WRAPPER/Contents/SharedSupport"
STEAM="$SS/prefix/drive_c/Program Files (x86)/Steam/steam.exe"
if [ ! -x "$SS/wine/bin/wine64" ] || [ ! -f "$STEAM" ]; then
  osascript -e 'on run a' -e 'display alert (item 2 of a) message (item 1 of a) as critical' -e 'end run' -- "The Windows Steam is missing or incomplete. Re-run scripts/make-steam-shortcut.sh from the repo." "$TITLE" >/dev/null 2>&1
  exit 1
fi
export WINEPREFIX="$SS/prefix"
export PATH="$SS/wine/bin:$PATH"
export DYLD_FALLBACK_LIBRARY_PATH="$WRAPPER/Contents/Frameworks:$SS/wine/lib:/usr/lib:/usr/local/lib"
export WINEDEBUG=-all
export WINEDLLOVERRIDES="gameoverlayrenderer64=d;gameoverlayrenderer=d;winemenubuilder.exe=d"

# Is Steam already up IN THIS PREFIX? Attribute by open files, not by command line: a steam.exe
# re-exec'd by its own updater carries a Windows-style argv no path-pgrep can see, and webhelper
# children always do (measured 2026-08-24).
running=""
for p in $(pgrep -f "steam.exe" 2>/dev/null); do
  case "$(ps -o command= -p "$p" 2>/dev/null)" in *steamwebhelper*) continue ;; esac
  lsof -p "$p" 2>/dev/null | grep -q "$SS/prefix" && { running=$p; break; }
done

if [ -n "$running" ]; then
  # Forward an open-main to the running instance — Steam raises its own window.
  # ⚠ NEVER `nohup` here (nor `env`, `setsid`, `bash -c`). macOS PURGES DYLD_* when exec'ing a
  # SIP-protected system binary, and this engine's win32u.so has only an `@loader_path/` rpath,
  # so stripping DYLD_FALLBACK_LIBRARY_PATH leaves wine unable to load its own
  # libfreetype.dylib and Steam renders with NO TEXT. Measured 2026-08-30 — it is why Steam had
  # no glyphs for a week while the game (launched directly) was fine.
  # `disown` is a shell builtin: no exec, nothing to strip.
  "$SS/wine/bin/wine64" "$STEAM" "steam://open/main" >/dev/null 2>&1 & disown
  osascript -e 'on run a' -e 'display notification (item 1 of a) with title (item 2 of a)' -e 'end run' -- "Steam is already running — bringing up its window." "$TITLE" >/dev/null 2>&1
else
  # a stale 0-byte .crash marker makes steam.exe exit 1 and never start — clear it first
  rm -f "$WINEPREFIX/drive_c/Program Files (x86)/Steam/.crash" 2>/dev/null
  # ⚠ NEVER `nohup` here (nor `env`, `setsid`, `bash -c`). macOS PURGES DYLD_* when exec'ing a
  # SIP-protected system binary, and this engine's win32u.so has only an `@loader_path/` rpath,
  # so stripping DYLD_FALLBACK_LIBRARY_PATH leaves wine unable to load its own
  # libfreetype.dylib and Steam renders with NO TEXT. Measured 2026-08-30 — it is why Steam had
  # no glyphs for a week while the game (launched directly) was fine.
  # `disown` is a shell builtin: no exec, nothing to strip.
  "$SS/wine/bin/wine64" "$STEAM" -no-cef-sandbox >/dev/null 2>&1 & disown
  osascript -e 'on run a' -e 'display notification (item 1 of a) with title (item 2 of a)' -e 'end run' -- "Starting the Windows Steam — its window takes about 20 s." "$TITLE" >/dev/null 2>&1
fi
exit 0
SHIM
chmod +x "$APP/Contents/MacOS/launch"

# ------------------------------------------------- icon (Steam's own, extracted locally)
ICON_OK=0
if command -v python3 >/dev/null 2>&1; then
  TMP=$(mktemp -d)
  if python3 "$(cd "$(dirname "$0")" && pwd)/pe-icon.py" "$STEAM_EXE" "$TMP/icon" >/dev/null 2>&1; then
    SRC=""
    [ -f "$TMP/icon.png" ] && SRC="$TMP/icon.png"
    [ -z "$SRC" ] && [ -f "$TMP/icon.ico" ] && sips -s format png "$TMP/icon.ico" --out "$TMP/icon.png" >/dev/null 2>&1 && SRC="$TMP/icon.png"
    if [ -n "$SRC" ]; then
      ISET="$TMP/steam.iconset"; mkdir -p "$ISET"
      for sz in 16 32 128 256 512; do
        sips -z $sz $sz          "$SRC" --out "$ISET/icon_${sz}x${sz}.png"    >/dev/null 2>&1
        sips -z $((sz*2)) $((sz*2)) "$SRC" --out "$ISET/icon_${sz}x${sz}@2x.png" >/dev/null 2>&1
      done
      iconutil -c icns "$ISET" -o "$APP/Contents/Resources/steamstore.icns" >/dev/null 2>&1 && ICON_OK=1 \
        && echo "    icon:    extracted from steam.exe"
    fi
  fi
  rm -rf "$TMP"
fi
[ "$ICON_OK" = 1 ] || echo "    icon:    skipped (generic) — python3 missing or extraction failed; the app still works"

# ------------------------------------------------- Info.plist
# The heredoc holds constants only. The name comes from --name and the prefix from a path, so plutil writes
# them and escapes them: written into the heredoc, a name holding & gave a plist that did not parse, exit 0.
# L1Prefix is kept only when it is absolute and the folder is there.
PL="$APP/Contents/Info.plist"
not_built() { echo "ERROR: $1; the app was not built"; rm -rf "$APP"; exit 1; }
L1PREFIX=""
case "$SS/prefix" in /*) if [ -d "$SS/prefix" ]; then L1PREFIX="$SS/prefix"; fi ;; esac
cat > "$PL" << PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key>      <string>$BUNDLE_ID</string>
    <key>CFBundleVersion</key>         <string>1.0</string>
    <key>CFBundlePackageType</key>     <string>APPL</string>
    <key>CFBundleExecutable</key>      <string>launch</string>$([ "$ICON_OK" = 1 ] && printf '\n    <key>CFBundleIconFile</key>        <string>steamstore.icns</string>')
    <key>LSMinimumSystemVersion</key>  <string>13.0</string>
    <key>NSHighResolutionCapable</key> <true/>
    <key>L1Role</key>                  <string>steam</string>
    <key>CFBundleAlternateNames</key>
    <array>
        <string>Windows Steam</string>
        <string>Steam Store</string>
        <string>CS2 Steam Store</string>
    </array>
</dict>
</plist>
PLIST
plutil -replace CFBundleName -string "$APPNAME" "$PL" >/dev/null 2>&1 || not_built "$PL is not a valid property list"
plutil -replace CFBundleDisplayName -string "$APPNAME" "$PL" >/dev/null 2>&1 || not_built "$PL is not a valid property list"
[ -z "$L1PREFIX" ] || plutil -replace L1Prefix -string "$L1PREFIX" "$PL" >/dev/null 2>&1 || not_built "$PL is not a valid property list"
plutil -lint "$PL" >/dev/null 2>&1 || not_built "$PL is not a valid property list"
/bin/bash -n "$APP/Contents/MacOS/launch" 2>/dev/null || not_built "$APP/Contents/MacOS/launch does not parse"

# ------------------------------------------------- the app this one replaces
# "CS2 Steam Store.app" in the same folder goes when it is this script's own and not the app just built:
# -ef, because the volume ignores letter case, so --name "cs2 steam store" names that very folder.
OLD="$DEST/CS2 Steam Store.app"
if [ -e "$OLD" ] || [ -L "$OLD" ]; then
  if [ "$OLD" -ef "$APP" ]; then :
  elif own_bundle "$OLD" "$MARK" "$BUNDLE_ID"; then
    rm -rf "$OLD"
    echo "    old app: removed $OLD, which this app replaces. A Dock entry for it has to be dragged out by hand."
  else
    echo "    old app: left $OLD: it was not built by this script"
  fi
fi

touch "$APP"
echo "=== done ==="
echo "Shop:  double-click  $APP   (the Windows Steam, wine 11.0 wrapper)"
echo "Play:  double-click  ~/Applications/Cities Skylines II.app   (game, 11.16 wrapper)"
echo "Licences are account-level — a purchase in one wrapper is immediately usable in the other."

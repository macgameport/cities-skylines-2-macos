#!/bin/bash
# make-app.sh -- build ~/Applications/Surviving Mars Relaunched.app, a double-click shim that runs
# launch-relaunched.sh quietly (SM_QUIET=1: notifications, alert on failure) and logs to
# ~/Library/Logs/sm-relaunched-launcher.log. Modelled on cs2's scripts/make-steam-shortcut.sh.
# Re-run this instead of editing the generated app. The icon is Relaunched's own, pulled from
# Mars.exe with cs2's scripts/pe-icon.py (the original); without it the app gets a generic icon.
# Each launch first pulls this repo from `hub main`, a private remote (one Mac is the only place the
# scripts are edited; a second Mac follows it), then runs the launcher it finds. Offline or with no
# such remote, the pull gives up in seconds and the installed scripts run. A change to this file still
# needs a manual re-run.
# SM_APP and SM_SCRIPT override the app path and the launcher it runs, for tools/test-make-app.sh.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
APP="${SM_APP:-$HOME/Applications/Surviving Mars Relaunched.app}"
SCRIPT="${SM_SCRIPT:-$HERE/launch-relaunched.sh}"
GAME_EXE="$HOME/Applications/SurvivingMars.app/Contents/SharedSupport/prefix/drive_c/Program Files (x86)/Steam/steamapps/common/Project Spark/Mars.exe"
PE_ICON="$HOME/github/cs2/scripts/pe-icon.py"

[ -f "$SCRIPT" ] || { echo "missing $SCRIPT"; exit 1; }
pgrep -f "$APP/Contents/MacOS/launch" >/dev/null && { echo "the app is running; quit the game first"; exit 1; }
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/MacOS/launch" <<SHIM
#!/bin/bash
# Generated by sm-patch/make-app.sh -- re-run that instead of editing this file.
SCRIPT="$SCRIPT"
GAME_EXE="$GAME_EXE"
LOG="\$HOME/Library/Logs/sm-relaunched-launcher.log"
mkdir -p "\$(dirname "\$LOG")"
if [ ! -f "\$SCRIPT" ]; then
  osascript -e 'display alert "Surviving Mars: Relaunched" message "Launcher script is missing. Re-run sm-patch/make-app.sh." as critical'
  exit 1
fi
# Match the START of the game's command line (its own path), never a substring: a pattern alone
# also matches any shell or editor that mentions the file (cs2 shortcut 2026-08-23; a monitoring
# loop refused a launch 2026-11-01). Same test as launch-relaunched.sh's game_running.
running=0
for p in \$(pgrep -f 'Mars\\.exe' 2>/dev/null); do
  case "\$(ps -o command= -p "\$p" 2>/dev/null)" in
    "\$GAME_EXE"*|'C:\\'*'\\Project Spark\\Mars.exe'*) running=1 ;;
  esac
done
if [ "\$running" = 1 ]; then
  osascript -e 'display notification "Already running. Click its window." with title "Surviving Mars: Relaunched"'
  exit 0
fi
{ echo; echo "===== \$(date '+%Y-%m-%d %H:%M:%S') ====="; } >> "\$LOG"
# Pull the latest scripts from the remote named hub before running them. Never fatal: offline, ssh gives up
# after 5 s and the installed scripts run; a local edit the pull would overwrite is kept and reported.
# Trust: this runs whatever it pulls, which is acceptable only when hub is a private repo you alone
# control (a local path, or SSH with your own key and host-key checking; BatchMode fails on an unknown
# or changed key) and --ff-only refuses a rewritten history. Never point hub at a shared remote.
# git writes a changed file as a new inode (measured 2026-11-08), so a launcher still shutting Steam
# down keeps reading its old copy (cs2 GOTCHAS 2026-10-10: rename over, never edit in place).
REPO="\$(dirname "\$SCRIPT")"
if command -v git >/dev/null 2>&1 && [ -d "\$REPO/.git" ]; then
  before=\$(git -C "\$REPO" rev-parse --short HEAD 2>/dev/null)
  if out=\$(GIT_TERMINAL_PROMPT=0 GIT_SSH_COMMAND='ssh -o BatchMode=yes -o ConnectTimeout=5' \\
            git -C "\$REPO" pull --ff-only --quiet hub main 2>&1); then
    after=\$(git -C "\$REPO" rev-parse --short HEAD 2>/dev/null)
    if [ "\$before" = "\$after" ]; then echo "scripts: current (\$after)"; else echo "scripts: updated \$before -> \$after"; fi
  else
    echo "scripts: pull failed, running the installed ones (\$before): \$(echo "\$out" | tail -n 1)"
  fi
fi >> "\$LOG" 2>&1
SM_QUIET=1 bash "\$SCRIPT" >> "\$LOG" 2>&1
rc=\$?
if [ \$rc -ne 0 ]; then
  osascript -e "display alert \"Surviving Mars: Relaunched\" message \"Launch failed (exit \$rc). Open the log?\" buttons {\"Dismiss\",\"Open Log\"} default button \"Open Log\"" \\
    -e 'if button returned of result is "Open Log" then do shell script "open ~/Library/Logs/sm-relaunched-launcher.log"' >/dev/null 2>&1
fi
exit \$rc
SHIM
chmod +x "$APP/Contents/MacOS/launch"

ICON_KEY=""
if [ -f "$PE_ICON" ] && [ -f "$GAME_EXE" ]; then
  TMP=$(mktemp -d)
  if python3 -I "$PE_ICON" "$GAME_EXE" "$TMP/icon" >/dev/null 2>&1; then
    SRC=""
    [ -f "$TMP/icon.png" ] && SRC="$TMP/icon.png"
    [ -z "$SRC" ] && [ -f "$TMP/icon.ico" ] && sips -s format png "$TMP/icon.ico" --out "$TMP/icon.png" >/dev/null 2>&1 && SRC="$TMP/icon.png"
    if [ -n "$SRC" ]; then
      ISET="$TMP/relaunched.iconset"; mkdir -p "$ISET"
      for sz in 16 32 128 256 512; do
        sips -z $sz $sz "$SRC" --out "$ISET/icon_${sz}x${sz}.png" >/dev/null 2>&1
        sips -z $((sz * 2)) $((sz * 2)) "$SRC" --out "$ISET/icon_${sz}x${sz}@2x.png" >/dev/null 2>&1
      done
      iconutil -c icns "$ISET" -o "$APP/Contents/Resources/relaunched.icns" >/dev/null 2>&1 \
        && ICON_KEY="<key>CFBundleIconFile</key>          <string>relaunched.icns</string>"
    fi
  fi
  rm -rf "$TMP"
fi

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>              <string>Surviving Mars Relaunched</string>
    <key>CFBundleDisplayName</key>       <string>Surviving Mars: Relaunched</string>
    <key>CFBundleIdentifier</key>        <string>local.sm-patch.relaunched.launcher</string>
    <key>CFBundleVersion</key>           <string>1.0</string>
    <key>CFBundlePackageType</key>       <string>APPL</string>
    <key>CFBundleExecutable</key>        <string>launch</string>
    $ICON_KEY
    <key>LSMinimumSystemVersion</key>    <string>13.0</string>
    <key>NSHighResolutionCapable</key>   <true/>
</dict>
</plist>
PLIST
plutil -lint "$APP/Contents/Info.plist" >/dev/null
touch "$APP"
echo "built: $APP"
if [ -n "$ICON_KEY" ]; then echo "icon:  from Mars.exe"; else echo "icon:  generic (pe-icon.py or Mars.exe not found)"; fi

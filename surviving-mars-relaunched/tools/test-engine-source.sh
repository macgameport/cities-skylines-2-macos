#!/bin/bash
# test-engine-source.sh -- which Wine tools/make-engine.sh (standalone) and tools/test-make-engine-install.sh build
# from (docs/plans/launcher-window.md, 2.4, W12): the S734M wrapper's while a wrapper of that name is in
# ~/Applications; the copy SurvivingMars.app keeps as wine.d3dm21-BAK when S734M.app is the Steam app or is not
# there; and, for make-engine.sh, ENGINE_SRC when it is set. HOME is a scratch folder of fixture bundles that
# hold no Wine, so each script stops at its first check of the Wine and names the path it chose: make-engine.sh
# in its "ERROR: no Wine engine at" line (exit 1), the install test in its "REFUSED" line (exit 2), before
# either makes or starts anything. No Wine, no Intel program, nothing written outside the scratch folder.
#   bash tools/test-engine-source.sh            exit 0 = every case passed
#   MUTANT=1 ...   make-engine.sh never looks at the kept copy; must exit 1
#   MUTANT=2 ...   make-engine.sh ignores ENGINE_SRC; must exit 1
#   MUTANT=3 ...   the install test never looks at the kept copy; must exit 1
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
T="$(mktemp -d /tmp/engine-source-test.XXXX)"
trap 'rm -rf "$T"' EXIT
M="${MUTANT:-0}"
mutated() { echo "REFUSED: mutant did not apply"; exit 2; }
case "$M" in 0|1|2|3) ;; *) echo "REFUSED: no mutant $M"; exit 2 ;; esac
fails=0
check() {  # <name> <got> <want>
  if [ "$2" = "$3" ]; then echo "PASS  $1"; else echo "FAIL  $1 (got '$2', want '$3')"; fails=$((fails + 1)); fi
}

# scratch copies of the two scripts, laid out as in the repo; a mutant edits one of them
mkdir -p "$T/sm/tools"
ME="$T/sm/tools/make-engine.sh"; IT="$T/sm/tools/test-make-engine-install.sh"
cp "$HERE/tools/make-engine.sh" "$ME"; cp "$HERE/tools/test-make-engine-install.sh" "$IT"
case "$M" in
  1) sed -i '' '/^  \[ -d "\$SRC" \] || SRC=.*wine\.d3dm21-BAK"$/d' "$ME"; grep -q 'SurvivingMars.app/Contents/SharedSupport/wine.d3dm21-BAK' "$ME" && mutated ;;
  2) sed -i '' 's/^  SRC="\${ENGINE_SRC:-\$SRC}"$/  SRC="$SRC"/' "$ME"; grep -q 'ENGINE_SRC:-' "$ME" && mutated ;;
  3) sed -i '' '/^\[ -d "\$SRCW" \] || SRCW=.*wine\.d3dm21-BAK"$/d' "$IT"; grep -q 'SurvivingMars.app/Contents/SharedSupport/wine.d3dm21-BAK' "$IT" && mutated ;;
esac

H="$T/home"; A="$H/Applications"
S734M_WINE="$A/S734M.app/Contents/SharedSupport/wine"
KEPT="$A/SurvivingMars.app/Contents/SharedSupport/wine.d3dm21-BAK"
reset() {   # <S734M.app: wrapper|app|none> <kept copy: yes|no>: the fixture home, every Wine folder empty
  rm -rf "$H"; mkdir -p "$A"
  case "$1" in
    wrapper) mkdir -p "$S734M_WINE/lib" "$A/S734M.app/Contents/SharedSupport/prefix" ;;
    app) mkdir -p "$A/S734M.app/Contents/MacOS"; printf '#!/bin/bash\n# Generated by scripts/make-steam-shortcut.sh\n' > "$A/S734M.app/Contents/MacOS/launch" ;;
  esac
  [ "$2" = yes ] && mkdir -p "$KEPT/lib"
  # the guard of this whole test: no wine64 anywhere, so neither script can go past its first check
  [ -z "$(find "$H" -name wine64)" ] || { echo "REFUSED: a wine64 is in the fixture home"; exit 2; }
}
engine() {   # [ENGINE_SRC]: make-engine.sh run plain; its exit code and the folder its ERROR line names
  local out rc
  if [ -n "${1:-}" ]; then out=$(cd "$T" && env -u CX_GPTK HOME="$H" ENGINE_SRC="$1" /bin/bash "$ME" 2>&1); rc=$?
  else out=$(cd "$T" && env -u CX_GPTK -u ENGINE_SRC HOME="$H" /bin/bash "$ME" 2>&1); rc=$?; fi
  echo "$rc:$(printf '%s\n' "$out" | sed -n 's/^ERROR: no Wine engine at //p')"
}
install_test() {   # the install test: its exit code and the folder its REFUSED line names
  local out rc
  out=$(cd "$T" && env -u ENGINE_SRC HOME="$H" /bin/bash "$IT" 2>&1); rc=$?
  echo "$rc:$(printf '%s\n' "$out" | sed -n 's/^REFUSED: no Wine to clone at //p')"
}

reset wrapper yes
check "a wrapper-shaped S734M.app: make-engine.sh takes its Wine" "$(engine)" "1:$S734M_WINE"
check "  ...and so does the install test" "$(install_test)" "2:$S734M_WINE"
check "  ...ENGINE_SRC still overrides make-engine.sh's choice" "$(engine "$T/elsewhere/wine")" "1:$T/elsewhere/wine"
reset app yes
check "S734M.app is the Steam app: make-engine.sh takes the kept copy" "$(engine)" "1:$KEPT"
check "  ...and so does the install test" "$(install_test)" "2:$KEPT"
reset none yes
check "no S734M.app: make-engine.sh takes the kept copy" "$(engine)" "1:$KEPT"
check "  ...and so does the install test" "$(install_test)" "2:$KEPT"
reset none no
check "neither is there: make-engine.sh names the kept copy's place" "$(engine)" "1:$KEPT"
check "  ...and so does the install test" "$(install_test)" "2:$KEPT"
check "nothing was made beside the scripts (the install test makes scratch/ only past its check)" "$(ls -A "$T/sm")" tools

echo "$fails failure(s)"
[ "$fails" = 0 ]

#!/bin/bash
# make-installer-app.sh -- build the double-click installer of one game and its ZIP, for a release page
# (docs/plans/simple-install.md, 2.5). The app is not in the repository and holds none of its code: its
# program is a short bash script that writes a .command file into a temporary folder and opens it in
# Terminal, where it fetches the root install.sh of its ref and runs it. So one published app keeps
# installing what that ref holds, and opening it again is the update.
#
#   bash common/make-installer-app.sh --dest <folder> --game <folder> (--icns <file> | --no-icon) [--ref <ref>]
#
#   --game    a game folder with a row in common/games.tsv; the app is "Install <its title without the colon>"
#   --ref     the branch the app follows; default release, the branch that moves forward only on purpose
#   --icns    the app's icon (the 14unch3r mark: ~/Applications/14unch3r.app/Contents/Resources/14unch3r.icns);
#             --no-icon says a generic icon is meant. One of the two must be given.
#   exit 0 = built, and the ZIP's size and sha256 printed; 1 = refused or failed, said why; 2 = a wrong option.
# It replaces only its own app (its identifier, and its marker in the program's second line), builds in a
# hidden folder inside --dest, removed when it exits, and swaps the finished app in.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
GAMES="$HERE/games.tsv"
ID="local.1launcher.installer"
MARK="# Generated by common/make-installer-app.sh -- run that again instead of editing this file."
DEST=""; GAME=""; REF="release"; ICNS=""; NOICON=0

need_value() {   # <option> [<value> ...]: an option that takes a value must be given a non-empty one
  if [ $# -lt 2 ] || [ -z "$2" ]; then echo "$1 needs a value"; exit 2; fi
}
while [ $# -gt 0 ]; do
  case "$1" in
    --dest) need_value "$@"; DEST="$2"; shift 2 ;;
    --game) need_value "$@"; GAME="$2"; shift 2 ;;
    --ref) need_value "$@"; REF="$2"; shift 2 ;;
    --icns) need_value "$@"; ICNS="$2"; shift 2 ;;
    --no-icon) NOICON=1; shift ;;
    -h|--help) sed -n '2,/^set -u$/p' "$0" | sed '$d'; exit 0 ;;
    *) echo "unknown option: $1 (try --help)"; exit 2 ;;
  esac
done
[ -n "$DEST" ] || { echo "--dest <folder> is needed"; exit 2; }
[ -n "$GAME" ] || { echo "--game <folder> is needed"; exit 2; }
if [ -n "$ICNS" ] && [ "$NOICON" = 1 ]; then echo "--icns and --no-icon cannot both be given"; exit 2; fi
if [ -z "$ICNS" ] && [ "$NOICON" = 0 ]; then echo "give --icns <file>, or --no-icon when a generic icon is meant"; exit 2; fi
if [ -n "$ICNS" ] && [ ! -f "$ICNS" ]; then echo "--icns: no such file: $ICNS"; exit 2; fi
printf '%s' "$GAME" | grep -Eq '^[a-z0-9][a-z0-9-]*$' || { echo "not a game folder: $GAME"; exit 2; }
case "$REF" in -*|/*|*..*|*//*) echo "not a branch, tag or commit of this repository: $REF"; exit 2 ;; esac
printf '%s' "$REF" | grep -Eq '^[A-Za-z0-9._/-]+$' || { echo "not a branch, tag or commit of this repository: $REF"; exit 2; }
TITLE="$(awk -F'\t' -v g="$GAME" '$2 == g { print $3; exit }' "$GAMES" 2>/dev/null | tr -d ':')"
[ -n "$TITLE" ] || { echo "common/games.tsv has no row for $GAME"; exit 2; }
printf '%s' "$TITLE" | grep -Eq '^[A-Za-z0-9 ]+$' || { echo "the title of $GAME holds a character an app name here cannot: $TITLE"; exit 2; }

DEST="${DEST%/}"
NAME="Install $TITLE"
APP="$DEST/$NAME.app"
ZIP="$DEST/$(printf '%s' "$NAME" | tr ' ' '-').zip"

own_app() {   # <target>: 0 when it is absent or this builder's own app
  local t="$1" id
  [ -e "$t" ] || [ -L "$t" ] || return 0
  { [ -d "$t" ] && [ ! -L "$t" ]; } || return 1
  id=$(plutil -extract CFBundleIdentifier raw "$t/Contents/Info.plist" 2>/dev/null) || return 1
  [ "$id" = "$ID" ] || return 1
  [ "$(sed -n 2p "$t/Contents/MacOS/install" 2>/dev/null)" = "$MARK" ]
}

echo "=== building $APP ==="
if ! own_app "$APP"; then
  echo "ERROR: $APP exists and was not built by this script; nothing removed"
  exit 1
fi
mkdir -p "$DEST" || { echo "ERROR: cannot make $DEST"; exit 1; }
B="$(mktemp -d "$DEST/.installer-build.XXXXXX")" || { echo "ERROR: cannot make a build folder in $DEST"; exit 1; }
trap 'rm -rf "$B"' EXIT
NEW="$B/$NAME.app"
mkdir -p "$NEW/Contents/MacOS" "$NEW/Contents/Resources"

# The program. @GAME@, @REF@ and @TITLE@ are written in below; each was checked above, so none can end a quote.
cat > "$NEW/Contents/MacOS/install" << 'SHIM'
#!/bin/bash
# Generated by common/make-installer-app.sh -- run that again instead of editing this file.
D="$(mktemp -d "${TMPDIR:-/tmp}/1launcher-install.XXXXXX" 2>/dev/null)" \
  || D="$(mktemp -d /tmp/1launcher-install.XXXXXX 2>/dev/null)" || {
  osascript -e 'on run a' -e 'display alert ("Install " & item 1 of a) message "A temporary folder could not be made. Restart the Mac, then open the installer again." as critical' -e 'end run' -- "@TITLE@"
  exit 1
}
C="$D/Install @TITLE@.command"
cat > "$C" <<'EOS'
#!/bin/bash
trap 'rm -f "$0"; rmdir "$(dirname "$0")" 2>/dev/null' EXIT
clear
echo "Fetching the installer from github.com/macgameport/1launcher ..."
S="$(curl --proto '=https' --tlsv1.2 -fsSL "https://raw.githubusercontent.com/macgameport/1launcher/@REF@/install.sh")"; rc=$?
if [ "$rc" = 0 ]; then
  /bin/bash -c "$S" 1launcher-install @GAME@ "@REF@"
elif [ "$rc" = 22 ]; then
  echo "This installer has been withdrawn or has moved. The guide has the current one:"
  echo "  https://github.com/macgameport/1launcher/blob/main/@GAME@/INSTALL.md"
else
  echo "GitHub could not be reached. Check the network, then open the installer again."
fi
echo; echo "You can close this window."
EOS
chmod +x "$C"
open -a Terminal "$C"
SHIM
sed -i '' -e "s#@GAME@#$GAME#g" -e "s#@REF@#$REF#g" -e "s#@TITLE@#$TITLE#g" "$NEW/Contents/MacOS/install"
chmod +x "$NEW/Contents/MacOS/install"
[ "$(sed -n 2p "$NEW/Contents/MacOS/install")" = "$MARK" ] || { echo "ERROR: the program's marker line is not where it should be"; exit 1; }

ICON_OK=0
if [ -n "$ICNS" ]; then
  cp "$ICNS" "$NEW/Contents/Resources/installer.icns" && ICON_OK=1
  [ "$ICON_OK" = 1 ] || { echo "ERROR: the icon could not be copied"; exit 1; }
  echo "    icon:     $(basename "$ICNS")"
else
  echo "    icon:     none, as asked (--no-icon); the app shows the generic icon"
fi

# The heredoc holds constants only; the name comes from the games table, so plutil writes it and escapes it.
# LSArchitecturePriority: so that macOS does not offer Rosetta for a program that is a script (not verified).
PL="$NEW/Contents/Info.plist"
not_built() { echo "ERROR: $PL is not a valid property list; the app was not built"; exit 1; }
cat > "$PL" << 'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key>      <string>local.1launcher.installer</string>
    <key>CFBundleExecutable</key>      <string>install</string>
    <key>CFBundlePackageType</key>     <string>APPL</string>
    <key>CFBundleVersion</key>         <string>1</string>
    <key>LSMinimumSystemVersion</key>  <string>13.0</string>
    <key>LSArchitecturePriority</key>
    <array>
        <string>arm64</string>
    </array>
</dict>
</plist>
PLIST
plutil -replace CFBundleName -string "$NAME" "$PL" > /dev/null 2>&1 || not_built
plutil -replace CFBundleDisplayName -string "$NAME" "$PL" > /dev/null 2>&1 || not_built
if [ "$ICON_OK" = 1 ]; then plutil -replace CFBundleIconFile -string installer.icns "$PL" > /dev/null 2>&1 || not_built; fi
plutil -lint "$PL" > /dev/null 2>&1 || not_built

# The swap: the old app into the build folder, the new one into its place, the old one back if that fails.
if [ -e "$APP" ]; then
  mv "$APP" "$B/old.app" || { echo "ERROR: could not move the old app aside; nothing was changed"; exit 1; }
  if ! mv "$NEW" "$APP"; then
    mv "$B/old.app" "$APP"
    echo "ERROR: could not move the new app into place; the old one is back"
    exit 1
  fi
else
  mv "$NEW" "$APP" || { echo "ERROR: could not move the new app into place"; exit 1; }
fi
rm -f "$ZIP"
ditto -c -k --keepParent "$APP" "$ZIP" || { echo "ERROR: the ZIP could not be made"; exit 1; }
echo "=== done ==="
echo "App:  $APP  (follows $REF)"
echo "ZIP:  $ZIP"
echo "      $(stat -f %z "$ZIP") bytes, sha256 $(shasum -a 256 "$ZIP" | awk '{ print $1 }')"
